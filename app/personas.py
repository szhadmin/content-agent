"""人设预设库 + 平台写作/排版规则。

设计原则
--------
1. **预设不是替用户写死**：每个预设给一份能直接用的 persona（人设）、topic_domain（选题领域）、
   style_prompt（专属写作规范，留空就吃全局）、theme（排版主题）、image_count（配图数），
   用户选完还能在账号页里逐字改。
2. **写作规范和排版分开**：预设管「怎么写」，render.py 的主题管「长什么样」。两者在预设里
   有个推荐搭配（tech 博主配 tech 蓝），但不强绑。
3. **平台差异单独成表**：同一篇稿子在公众号和头条号的规矩不一样（标题字数、话题标签、
   段落长短），写作时按平台拼进提示词，别再把公众号的「反问+结论 ≤15 字」硬套给头条。

新增博主类型的成本：往 PERSONA_PRESETS 里加一条即可，账号页/编辑页自动出现。
"""
