def negative_terms(*, portrait: bool = True) -> list[str]:
    """完整负向词表。SD 的 `negative_prompt` 用它（那边能吃几十个词）。

    顺序有讲究：结构/解剖和文字排在最前面——词表被截断时先丢的是质感那几条，
    不能把"穿模、多手多脚"丢掉。
    """
    terms = list(_NEG_ANATOMY) + list(_NEG_TEXT) + list(_NEG_RENDER) + list(_NEG_LIGHT)
    terms += list(_NEG_DEFECT)
    if portrait:
        terms += _NEG_SURFACE + _NEG_POSE
    else:
        terms = [t for t in terms if t not in ("完美对称的脸", "左右完全一样的五官",
                                               "玻璃眼球的高光点", "面部扭曲")]
    # 去重保序
    seen: set[str] = set()
    out: list[str] = []
    for t in terms:
        if t not in seen:
            seen.add(t)
            out.append(t)
    return out


# 只吃单条 prompt 的后端扛不住几十个否定词：写太长模型会开始丢前面的指令。
# 挑最要命的十几个——结构错误优先，其次"画面里长字"，最后才是质感。
_NEG_CORE = [
    "穿模", "肢体穿插", "多出来的手脚", "两条腿黏连", "关节反折",
    "人体比例失调", "五官错位", "画面里任何文字/招牌/价签/水印",
    "塑料感皮肤", "过度磨皮", "CG 渲染感", "完美对称的脸",
]


def negative_clause(*, portrait: bool = True) -> str:
    """自然语言否定段（OpenAI images / 万相这种单条 prompt 的后端用）。"""
    terms = _NEG_CORE if portrait else [t for t in _NEG_CORE
                                        if t not in ("塑料感皮肤", "过度磨皮", "完美对称的脸")]
    return "画面里不要出现：" + "、".join(terms) + "。"


# 正向的解剖约束。负向词只能"减弱"，正向说清楚"要什么样"才真的能压住穿模，
# 实测比单纯堆否定词有效——尤其是全身图和四肢交叠的姿势。
ANATOMY_RULE = (
    "人体结构必须正确：四肢完整、各自分开，左右腿清晰可辨；手臂不穿过身体、不与躯干粘连；"
    "手指数量正常、自然弯曲；关节只朝正常方向弯曲；"
    "全身入镜时双腿自然分开站立或走姿，避免双腿重叠交叉。"
)


