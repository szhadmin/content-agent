def _pick(seq: list[Any], i: int) -> Any:
    return seq[i % len(seq)] if seq else None


def plan(idx: int = 0, *, portrait: bool = True, style: str = "auto",
         look: str = "", scene_hint: str = "") -> dict[str, str]:
    """给这一次出图定一份拍摄方案。

    idx     每出一次图 +1，用它轮换焦距/光线/构图，连拍才不会像复制粘贴。
    portrait 画面里有没有具体的人（有人脸才需要皮肤、表情、发型那几项）。
    style   STYLES 里的 key；"auto" 时按 portrait 选纪实或自然光。
    look    人物外形描述（虚拟人物号用），会原样带进「同一个人」的说明里。
    scene_hint 账号/人物自己的画面偏好。
    """
    st = STYLES.get(style or "auto") or STYLES["auto"]

    # auto：人像走纪实抓拍（最不容易出塑料感），静物走自然光小光圈。
    # 取模直接用 idx：词库长度 6/7/5/6/4 互不整除，所以相邻的几张一定会换参数，
    # 而且不会像"idx*3"那样因为和长度有公因数而只转到两三个值上。
    if not st.get("camera"):
        cam, depth = _pick(_CAMERAS, idx)
        light, wb = _pick(_LIGHTS, idx)
    else:
        cam = st["camera"]
        depth = st.get("depth") or _pick(_CAMERAS, idx)[1]
        lights = st.get("lights") or _LIGHTS
        light, wb = lights[idx % len(lights)]

    d = {
        "camera": cam,
        "depth": depth,
        "light": light,
        "white_balance": wb,
        "color": st.get("color") or _pick(_COLORS, idx),
        "frame": _pick(_FRAMES, idx),
        "flaw": _pick(_FLAWS, idx),
        "grain": _pick(_TEXTURE_FILM, idx + 1),
    }
    if portrait:
        d["skin"] = _pick(_TEXTURE_SKIN, idx)
        d["hair"] = _pick(_TEXTURE_HAIR, idx)
        d["expression"] = _pick(_EXPRESSIONS, idx)
    d["material"] = _pick(_TEXTURE_MAT, idx)
    if look:
        d["look"] = look
    if scene_hint:
        d["scene_hint"] = scene_hint
    return d


def prompt_block(p: dict[str, str], *, portrait: bool = True) -> str:
    """把方案拼成一段「拍摄说明」。按摄影的逻辑排序：器材 → 光 → 质感 → 构图 → 瑕疵。"""
    lines = [
        f"拍法：{p['camera']}；{p['depth']}。",
        f"光：{p['light']}；{p['white_balance']}。",
        f"调子：{p['color']}。",
    ]
    if portrait:
        if p.get("skin"):
            lines.append(f"皮肤：{p['skin']}。")
        if p.get("hair"):
            lines.append(f"头发：{p['hair']}。")
        if p.get("look"):
            lines.append(f"这个人长这样（每张图都必须是同一个人）：{p['look']}。")
        if p.get("expression"):
            lines.append(f"表情：{p['expression']}。")
    if p.get("material"):
        lines.append(f"材质：{p['material']}。")
    if p.get("scene_hint"):
        # 这是账号/人物自己填的题材偏好，和上面的「光」可能撞（比如写"暖色自然光"但这次排到
        # 正午硬光）。所以标明优先级：题材听它，光线听上面那条。
        lines.append(f"题材与氛围偏好（光以「光」那条为准）：{p['scene_hint']}。")
    lines.append(f"画质：{p['grain']}。")
    lines.append(f"构图：{p['frame']}。")
    lines.append(f"状态：{p['flaw']}。")
    return "\n".join(lines)


