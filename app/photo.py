"""写实摄影提示词工程：把「一句场景」变成一段像摄影师写下的拍摄说明。

为什么单独一个模块
------------------
`aigen.build_prompt` 原来只写「高质量写实照片 + 画面风格 + 别摆拍」。这类提示词的问题是
**全是形容词、没有一个决定画面的具体量**：模型只会给出一张「干净、均匀、无瑕疵」的图——
也就是最典型的 AI 味。

真人拍的照片之所以一眼能认出是「照片」，靠的不是「高清」「8K」这类词，而是这些：

  1. **一段明确的焦距和光圈**——透视和景深从这儿来，不是靠「浅景深」三个字。
  2. **一个有方向的光**——主光从哪儿来、暗部靠什么补、白平衡准不准。均匀打光必出塑料感。
  3. **允许不完美**——歪一点的地平线、前景遮挡、高光溢出、轻微手抖、边缘发软。
  4. **可数的细节**——毛孔、碎发、布料褶皱的阴影、嘴干纹，而不是「细节丰富」。
  5. **动作进行中**——不是摆好等按快门，是快门刚好按在这个动作里。

反过来，提示词里出现 `masterpiece`、`8k`、`ultra detailed`、`perfect lighting` 这类词，
几乎必然把画面推向「渲染图」而不是「照片」。本模块刻意一个都不用。

用法
----
    plan = photo.plan(idx, portrait=True, style="auto")   # idx 每次换，方案就换
    text = photo.prompt_block(plan)                        # 拼进正向提示词
    neg  = photo.negative_terms(portrait=True)             # SD 走 negative_prompt
    neg_txt = photo.negative_clause(portrait=True)         # 只吃单条 prompt 的后端用它

`plan()` 是纯函数（只依赖 idx 和 style），好处是同一篇文章重生成同一个 idx 得到同一份方案，
排查「为什么这张图难看」时能复现；要换画面就换 idx。
"""
